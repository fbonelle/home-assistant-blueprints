"""Build the four notification system blueprints. No Python is installed in Home Assistant."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import versioning  # noqa: E402  (tools/versioning.py: version scheme shared by all families)
import yaml

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'src/notification_system'

# Source file -> published blueprint, relative to the repository root.
BLUEPRINTS = {
    'sender.yaml': 'blueprints/script/notification_system/channel_sender.yaml',
    'dispatcher.yaml': 'blueprints/script/notification_system/dispatcher.yaml',
    'tts.yaml': 'blueprints/script/notification_system/text_to_speech.yaml',
    'relay.yaml': 'blueprints/automation/notification_system/mobile_relay.yaml',
}


class Input(str):
    pass


class Loader(yaml.SafeLoader):
    pass


class Dumper(yaml.SafeDumper):
    pass


Loader.add_constructor('!input', lambda loader, node: Input(loader.construct_scalar(node)))
Dumper.add_representer(Input, lambda dumper, value: dumper.represent_scalar('!input', value))
Dumper.add_representer(str, lambda d, v: d.represent_scalar(
    'tag:yaml.org,2002:str', '\n'.join(x.rstrip() for x in v.split('\n')), style='|' if '\n' in v else None))


def build():
    version = versioning.read('notification_system')
    for source, target in BLUEPRINTS.items():
        blueprint = versioning.with_min_version(yaml.load((BASE / source).read_text(), Loader=Loader))
        blueprint['blueprint']['name'] += ' — ' + version
        out = ROOT / target
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text('# SPDX-License-Identifier: GPL-3.0-only\n'
                       '# Generated by tools/build_notifications.py; edit src/notification_system/.\n' +
                       yaml.dump(blueprint, Dumper=Dumper, allow_unicode=True, sort_keys=False, width=110))
    examples = ROOT / 'examples/notification_system'
    examples.mkdir(parents=True, exist_ok=True)
    (examples / 'package.yaml').write_text((BASE / 'package.yaml').read_text())


if __name__ == '__main__':
    build()
