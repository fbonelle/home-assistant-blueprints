"""Build the standalone STYRBAR blueprint. No Python is installed in Home Assistant."""
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'src/ikea_styrbar_light'

class Input(str):
    pass

class Loader(yaml.SafeLoader):
    pass

class Dumper(yaml.SafeDumper):
    pass

Loader.add_constructor('!input', lambda loader, node: Input(loader.construct_scalar(node)))
Dumper.add_representer(Input, lambda dumper, value: dumper.represent_scalar('!input', value))
Dumper.add_representer(str, lambda d, v: d.represent_scalar(
    'tag:yaml.org,2002:str', v, style='|' if '\n' in v else None))

def rgb_xy(rgb):
    """The RGB-to-xy matrix used by Home Assistant, without device-specific clipping."""
    r, g, b = [v / 255 for v in rgb]
    r, g, b = [((v + .055) / 1.055) ** 2.4 if v > .04045 else v / 12.92 for v in (r, g, b)]
    x = r * .664511 + g * .154324 + b * .162028
    y = r * .283881 + g * .668433 + b * .047685
    z = r * .000088 + g * .072310 + b * .986039
    return [round(x / (x + y + z), 6), round(y / (x + y + z), 6)]

def build():
    version = (BASE / 'VERSION').read_text().strip()
    assert re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', version)
    blueprint = yaml.load((BASE / 'blueprint.yaml').read_text(), Loader=Loader)
    catalog = yaml.safe_load((BASE / 'palette.yaml').read_text())
    options = []
    for key, row in catalog.items():
        options.append(dict(value=key, label=row.pop('name')))
        if 'rgb_color' in row:
            row['xy'] = rgb_xy(row['rgb_color'])
        else:
            row['xy'] = row['xy_color']
    blueprint['blueprint']['name'] += ' — ' + version
    blueprint['blueprint']['input']['palette']['selector']['select']['options'] = options
    blueprint['variables']['catalog'] = catalog
    def expand(value):
        if isinstance(value, str) and value.startswith('@template:'):
            return (BASE / (value.split(':', 1)[1] + '.jinja')).read_text()
        if isinstance(value, dict):
            return {k: expand(v) for k, v in value.items()}
        if isinstance(value, list):
            return [expand(v) for v in value]
        return value
    blueprint = expand(blueprint)
    out = ROOT / 'blueprints/automation/ikea_styrbar_light/lampe_styrbar.yaml'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('# SPDX-License-Identifier: GPL-3.0-only\n# Generated by tools/build_styrbar.py; edit src/ikea_styrbar_light/.\n' +
                   yaml.dump(blueprint, Dumper=Dumper, allow_unicode=True, sort_keys=False, width=110))
    examples = ROOT / 'examples/ikea_styrbar_light'
    examples.mkdir(parents=True, exist_ok=True)
    for name in ['automations.yaml', 'helpers.yaml']:
        (examples / name).write_text((BASE / name).read_text())

if __name__ == '__main__':
    build()
