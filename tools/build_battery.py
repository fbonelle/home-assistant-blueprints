"""Build the standalone battery watch blueprint. No Python is installed in Home Assistant."""
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / 'src/battery_watch'

class Input(str):
    pass

class Loader(yaml.SafeLoader):
    pass

class Dumper(yaml.SafeDumper):
    pass

Loader.add_constructor('!input', lambda loader, node: Input(loader.construct_scalar(node)))
Dumper.add_representer(Input, lambda dumper, value: dumper.represent_scalar('!input', value))
Dumper.add_representer(str, lambda d, v: d.represent_scalar(
    'tag:yaml.org,2002:str', '\n'.join(x.rstrip() for x in v.split('\n')), style='|' if '\n' in v else None))

def build():
    version = (BASE / 'VERSION').read_text().strip()
    assert re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', version), 'Invalid blueprint version'
    blueprint = yaml.load((BASE / 'blueprint.yaml').read_text(), Loader=Loader)
    blueprint['blueprint']['name'] += ' — ' + version
    def expand(value):
        if isinstance(value, str) and value.startswith('@template:'):
            return (BASE / (value.split(':', 1)[1] + '.jinja')).read_text()
        if isinstance(value, dict):
            return {k: expand(v) for k, v in value.items()}
        if isinstance(value, list):
            return [expand(v) for v in value]
        return value
    blueprint = expand(blueprint)
    out = ROOT / 'blueprints/automation/battery_watch/surveillance_piles.yaml'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('# SPDX-License-Identifier: GPL-3.0-only\n# Generated by tools/build_battery.py; edit src/battery_watch/.\n' +
                   yaml.dump(blueprint, Dumper=Dumper, allow_unicode=True, sort_keys=False, width=110))
    examples = ROOT / 'examples/battery_watch'
    examples.mkdir(parents=True, exist_ok=True)
    (examples / 'automations.yaml').write_text((BASE / 'automations.yaml').read_text())

if __name__ == '__main__':
    build()
